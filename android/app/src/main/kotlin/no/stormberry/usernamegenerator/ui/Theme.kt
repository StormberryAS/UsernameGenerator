package no.stormberry.usernamegenerator.ui

import androidx.compose.foundation.isSystemInDarkTheme
import androidx.compose.material3.MaterialTheme
import androidx.compose.material3.Typography
import androidx.compose.material3.darkColorScheme
import androidx.compose.runtime.Composable
import androidx.compose.ui.graphics.Color
import androidx.compose.ui.text.TextStyle
import androidx.compose.ui.text.font.Font
import androidx.compose.ui.text.font.FontFamily
import androidx.compose.ui.text.font.FontWeight
import androidx.compose.ui.unit.sp
import no.stormberry.usernamegenerator.R

/**
 * The Stormberry dark glassmorphism palette, lifted verbatim from the web app's
 * style.css custom properties so the APK and username.stormberry.as look like one
 * product. The app is dark-only by design; [isSystemInDarkTheme] is deliberately
 * not consulted, because a light variant of this palette does not exist yet.
 */
object Stormberry {
    val Background = Color(0xFF0A0A0C)
    val Surface = Color(0xFF121216)
    val GlassFill = Color(0x08FFFFFF)
    val GlassBorder = Color(0x14FFFFFF)
    val TextMain = Color(0xFFFFFFFF)
    val TextMuted = Color(0xFF8A8A93)

    /**
     * The footer's colours. [TextMuted] is 5.8:1 on [Background], enough for a hint but dim for
     * a sentence that credits the word-list source, so the credit and the bold privacy line
     * use [TextSoft] (10.1:1) and the small print uses [TextSmallPrint] (7.1:1). Every footer
     * text colour is at least 4.5:1 on [Background]; the measured figures are in BUILD-3.md.
     */
    val TextSoft = Color(0xFFB8B8C2)
    val TextSmallPrint = Color(0xFF9A9AA4)

    /** The footer's top hairline and the divider inside it: white at 7% and 5%, as the web's. */
    val BorderFooter = Color(0x12FFFFFF)
    val BorderSoft = Color(0x0DFFFFFF)

    /**
     * The dot of the "Stormberry." wordmark. The web page paints it with a gradient from #E21E26
     * to #FF4D54 (footer.css, .footer-dot); on a glyph this small the gradient reads as the colour
     * between them, so the app uses that one colour and matches the page (where app and page
     * differ, the page wins). Decoration only; the word is the text beside it.
     */
    val BrandDot = Color(0xFFF03A40)

    val AccentIndigo = Color(0xFF4F46E5)
    val AccentRose = Color(0xFFE11D48)
    val AccentSky = Color(0xFF0EA5E9)
    val AccentEmerald = Color(0xFF10B981)
}

private val StormberryColors = darkColorScheme(
    primary = Stormberry.AccentIndigo,
    onPrimary = Stormberry.TextMain,
    secondary = Stormberry.AccentSky,
    onSecondary = Stormberry.TextMain,
    tertiary = Stormberry.AccentRose,
    background = Stormberry.Background,
    onBackground = Stormberry.TextMain,
    surface = Stormberry.Surface,
    onSurface = Stormberry.TextMain,
    surfaceVariant = Stormberry.Surface,
    onSurfaceVariant = Stormberry.TextMuted,
    outline = Stormberry.GlassBorder,
)

/**
 * Inter, the typeface username.stormberry.as self-hosts from fonts/inter/, so the APK and the
 * site set text in the same face. Four static instances of that same InterVariable.woff2, one
 * per weight this app uses, live in res/font and are regenerated by tools/build-inter-fonts.py.
 * Bundled in the APK: no downloadable-fonts provider, no network. A weight not listed here
 * would be faked by synthesis, so add an instance before using one.
 */
val Inter = FontFamily(
    Font(R.font.inter_regular, FontWeight.Normal),
    Font(R.font.inter_medium, FontWeight.Medium),
    Font(R.font.inter_semibold, FontWeight.SemiBold),
    Font(R.font.inter_bold, FontWeight.Bold),
)

/** Every Material 3 text style, set in [family]. Text with no explicit style inherits bodyLarge. */
private fun Typography.withFontFamily(family: FontFamily) = copy(
    displayLarge = displayLarge.copy(fontFamily = family),
    displayMedium = displayMedium.copy(fontFamily = family),
    displaySmall = displaySmall.copy(fontFamily = family),
    headlineLarge = headlineLarge.copy(fontFamily = family),
    headlineMedium = headlineMedium.copy(fontFamily = family),
    headlineSmall = headlineSmall.copy(fontFamily = family),
    titleLarge = titleLarge.copy(fontFamily = family),
    titleMedium = titleMedium.copy(fontFamily = family),
    titleSmall = titleSmall.copy(fontFamily = family),
    bodyLarge = bodyLarge.copy(fontFamily = family),
    bodyMedium = bodyMedium.copy(fontFamily = family),
    bodySmall = bodySmall.copy(fontFamily = family),
    labelLarge = labelLarge.copy(fontFamily = family),
    labelMedium = labelMedium.copy(fontFamily = family),
    labelSmall = labelSmall.copy(fontFamily = family),
)

private val StormberryTypography = Typography().withFontFamily(Inter).run {
    copy(
        displaySmall = displaySmall.copy(fontWeight = FontWeight.Bold, letterSpacing = (-0.5).sp),
        headlineSmall = headlineSmall.copy(fontWeight = FontWeight.Bold, letterSpacing = (-0.5).sp),
        titleMedium = titleMedium.copy(fontWeight = FontWeight.SemiBold),
        labelLarge = labelLarge.copy(fontWeight = FontWeight.Medium),
    )
}

/**
 * The generated username itself, sized to stay readable when it gets long. A standalone style
 * rather than one from the typography, so it names Inter itself.
 */
val UsernameTextStyle = TextStyle(
    fontFamily = Inter,
    fontSize = 30.sp,
    lineHeight = 38.sp,
    fontWeight = FontWeight.Bold,
    letterSpacing = (-0.5).sp,
)

@Composable
fun UsernameGeneratorTheme(content: @Composable () -> Unit) {
    MaterialTheme(
        colorScheme = StormberryColors,
        typography = StormberryTypography,
        content = content,
    )
}
